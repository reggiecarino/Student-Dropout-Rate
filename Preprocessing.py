"""3.1.2 Missing Values and Completeness of Data"""

import numpy as np

def summarize_features(df):
    feature_summary = []
    for col in df.columns:
        col_info = {
            'Feature Name': col,
            'Data Type': str(df[col].dtype),
            'Missing Values': df[col].isnull().sum()
        }

        if pd.api.types.is_numeric_dtype(df[col]):
            col_info['Category'] = 'Numerical'
            if df[col].nunique() < 20 and all(df[col].dropna().apply(lambda x: x == int(x))):
                col_info['Sub-Category'] = 'Discrete'
                col_info['Description'] = 'Counts or codes with a limited number of unique integer values.'
                col_info['Characteristics'] = f"Unique Values: {df[col].unique().tolist() if df[col].nunique() < 20 else 'Too many to list'}"
            else:
                col_info['Sub-Category'] = 'Continuous'
                col_info['Description'] = 'Measurements or quantities that can take any value within a range.'
                desc_stats = df[col].describe().loc[['mean', 'std', 'min', 'max']].to_dict()
                col_info['Characteristics'] = f"Mean: {desc_stats['mean']:.2f}, Std: {desc_stats['std']:.2f}, Min: {desc_stats['min']:.2f}, Max: {desc_stats['max']:.2f}"
        else:
            col_info['Category'] = 'Categorical'
            if df[col].nunique() / len(df) > 0.5: # Arbitrary threshold for high cardinality
                col_info['Sub-Category'] = 'Nominal (High Cardinality)'
                col_info['Description'] = 'Categories without inherent order, many unique values. Often identifiers.'
            elif df[col].nunique() <= 10:
                col_info['Sub-Category'] = 'Nominal/Ordinal'
                col_info['Description'] = 'Categories without/with inherent order, few unique values.'
            else:
                col_info['Sub-Category'] = 'Nominal'
                col_info['Description'] = 'Categories without inherent order.'
            col_info['Characteristics'] = f"Unique Values: {df[col].unique().tolist()}"

        feature_summary.append(col_info)
    return pd.DataFrame(feature_summary)

summary_df = summarize_features(df)

print("### Feature Type Summary\n")
