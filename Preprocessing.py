"""## 3.1.6 Detect Outliers using IQR


"""

print("### Outlier Detection using IQR Method\n")
outlier_results = {}

for col in numerical_continuous_cols:
    Q1 = df_processed[col].quantile(0.25)
    Q3 = df_processed[col].quantile(0.75)
    IQR = Q3 - Q1

    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    # Identify outliers
    outliers = df_processed[(df_processed[col] < lower_bound) | (df_processed[col] > upper_bound)]
    num_outliers = outliers.shape[0]
    percentage_outliers = (num_outliers / len(df_processed)) * 100

    outlier_results[col] = {
        'num_outliers': num_outliers,
        'percentage_outliers': percentage_outliers
    }

    print(f"Column: {col}")
    print(f"  Q1: {Q1:.2f}")
    print(f"  Q3: {Q3:.2f}")
    print(f"  IQR: {IQR:.2f}")
    print(f"  Lower Bound: {lower_bound:.2f}")
    print(f"  Upper Bound: {upper_bound:.2f}")
    print(f"  Number of Outliers: {num_outliers}")
    print(f"  Percentage of Outliers: {percentage_outliers:.2f}%\n")

print("Outlier detection complete for all numerical continuous columns.")

