"""## 3.4 Feature Selection

## 3.4.1 Feature Importance Analysis and Selection

To perform feature selection, we will use a `RandomForestClassifier` to identify the most important features. This involves training the model, extracting feature importances, and then visualizing the top features.
"""

from sklearn.ensemble import RandomForestClassifier
import matplotlib.pyplot as plt
import seaborn as sns
import numpy as np

# Prepare X (features) and y (target)
# Drop 'student_id' as it's an identifier and not a feature, and 'completion_status' as it's the target
X = df_processed_encoded.drop(columns=['student_id', 'completion_status'])
y = df_processed_encoded['completion_status']

# Encode the target variable: 'Completed' to 1, 'Dropped' to 0
y = y.map({'Completed': 1, 'Dropped': 0})

# Initialize and train a RandomForestClassifier
# Using a fixed random_state for reproducibility
rf_model = RandomForestClassifier(n_estimators=100, random_state=42, class_weight='balanced')
rf_model.fit(X, y)

# Get feature importances
feature_importances = rf_model.feature_importances_

# Create a DataFrame for better visualization and sorting
features_df = pd.DataFrame({
    'Feature': X.columns,
    'Importance': feature_importances
})

# Sort features by importance
features_df = features_df.sort_values(by='Importance', ascending=False)

print("Top 15 most important features:\n")
print(features_df.head(15).to_markdown(index=False))

# Visualize the top 15 most important features
plt.figure(figsize=(12, 8))
sns.barplot(x='Importance', y='Feature', data=features_df.head(15), palette='viridis')
plt.title('Top 15 Most Important Features')
plt.xlabel('Feature Importance')
plt.ylabel('Feature Name')
plt.tight_layout()
plt.show()

print("Bar chart of top 15 feature importances generated.")

