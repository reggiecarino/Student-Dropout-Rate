"""## 3.5 Dimensionality Reduction (PCA)

Principal Component Analysis (PCA) is a powerful technique for dimensionality reduction. It transforms a large set of variables into a smaller one that still contains most of the information in the large set. This can help to simplify models, reduce noise, and improve computational efficiency. Here, we'll apply PCA to the complete preprocessed feature set (`X`) to explore its structure.
"""

from sklearn.decomposition import PCA
import matplotlib.pyplot as plt
import numpy as np

# Initialize PCA
pca = PCA()

# Fit PCA to the full preprocessed feature set (X)
pca.fit(X)

# Plot the cumulative explained variance ratio
plt.figure(figsize=(10, 6))
plt.plot(np.cumsum(pca.explained_variance_ratio_))
plt.xlabel('Number of Components')
plt.ylabel('Cumulative Explained Variance')
plt.title('Cumulative Explained Variance by Number of Principal Components')
plt.grid(True)
plt.show()

print("Explained variance plot generated.")

import seaborn as sns

# Reduce dimensions to the first two principal components for visualization
pca_2d = PCA(n_components=2)
principal_components = pca_2d.fit_transform(X)

# Create a DataFrame for the principal components and the target variable
pca_df = pd.DataFrame(data=principal_components, columns=['Principal Component 1', 'Principal Component 2'])
pca_df['completion_status'] = y.values

# Visualize the first two principal components
plt.figure(figsize=(10, 8))
sns.scatterplot(
    x='Principal Component 1',
    y='Principal Component 2',
    hue='completion_status',
    data=pca_df,
    palette='viridis',
    alpha=0.7
)
plt.title('2D PCA Scatter Plot of Principal Components, Colored by Completion Status')
plt.xlabel('Principal Component 1')
plt.ylabel('Principal Component 2')
plt.grid(True)
plt.show()

print("2D PCA scatter plot generated.")

